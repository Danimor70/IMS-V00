export function resolveOperationalConfig(route: RouteId): OperationalModuleConfig {
  if (route.startsWith('processes-')) return OPERATIONAL_MODULES['processes-profile'];
  if (route.startsWith('risks-')) return OPERATIONAL_MODULES['risks-identify'];
  if (route.startsWith('audits-')) return OPERATIONAL_MODULES['audits-program'];
  if (route.startsWith('capa-')) return OPERATIONAL_MODULES['capa-nc'];
  if (route.startsWith('kpi-')) return OPERATIONAL_MODULES['kpi-objectives'];
  if (route.startsWith('hse-')) return OPERATIONAL_MODULES['hse-incidents'];
  return OPERATIONAL_MODULES[route] || OPERATIONAL_MODULES.cartable;
}
